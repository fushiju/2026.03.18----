"""生成品牌搜索、查看、编辑测试用例 Excel（各一个文件）"""
import sys, io
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')
import openpyxl
from openpyxl.styles import Font, Alignment, Border, Side, PatternFill


def create_excel(filename, sheet_title, cases):
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = sheet_title

    header_fill = PatternFill(start_color="4472C4", end_color="4472C4", fill_type="solid")
    header_font = Font(bold=True, size=11, color="FFFFFF")
    wrap = Alignment(wrap_text=True, vertical="top")
    center_top = Alignment(horizontal="center", vertical="top")
    thin_border = Border(
        left=Side(style='thin'), right=Side(style='thin'),
        top=Side(style='thin'), bottom=Side(style='thin')
    )
    priority_colors = {
        "P0": PatternFill(start_color="FF6B6B", end_color="FF6B6B", fill_type="solid"),
        "P1": PatternFill(start_color="FFA500", end_color="FFA500", fill_type="solid"),
        "P2": PatternFill(start_color="90EE90", end_color="90EE90", fill_type="solid"),
    }

    headers = ["用例编号", "测试分类", "用例名称", "优先级", "前置条件", "测试步骤", "预期结果"]
    col_widths = [14, 16, 30, 8, 28, 55, 55]

    for i, (h, w) in enumerate(zip(headers, col_widths), 1):
        cell = ws.cell(row=1, column=i, value=h)
        cell.font = header_font
        cell.fill = header_fill
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = thin_border
        ws.column_dimensions[chr(64 + i)].width = w

    for r, case in enumerate(cases, 2):
        for c, val in enumerate(case, 1):
            cell = ws.cell(row=r, column=c, value=val)
            cell.alignment = wrap
            cell.border = thin_border

    for r in range(2, len(cases) + 2):
        priority = ws.cell(row=r, column=4).value
        if priority in priority_colors:
            ws.cell(row=r, column=4).fill = priority_colors[priority]
            ws.cell(row=r, column=4).alignment = center_top
        ws.row_dimensions[r].height = 85

    wb.save(filename)
    p0 = sum(1 for c in cases if c[3] == "P0")
    p1 = sum(1 for c in cases if c[3] == "P1")
    p2 = sum(1 for c in cases if c[3] == "P2")
    print(f"  {filename}")
    print(f"  共 {len(cases)} 条 (P0:{p0} P1:{p1} P2:{p2})")


